def filler_text(n_words: int, seed) -> str:
    """Deterministic pseudo-prose. Distinct seeds give distinct (uncached) text."""
    rng = random.Random(f"filler:{seed}")
    out: list[str] = []
    n = 0
    while n < n_words:
        k = rng.randint(8, 22)
        words = [rng.choice(_WORDS) for _ in range(k)]
        words[0] = words[0].capitalize()
        out.append(" ".join(words) + ".")
        n += k
    return " ".join(out)


def count_tokens(url: str, model: str, messages) -> int | None:
    """Token count via vLLM's /tokenize (chat template applied). None when unavailable."""
    body = {"model": model, "messages": messages, "add_generation_prompt": True}
    req = urllib.request.Request(
        base_url(url) + "/tokenize",
        data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=300) as resp:
            data = json.loads(resp.read())
    except (OSError, urllib.error.URLError, ValueError):
        return None
    return int(data.get("count") or len(data.get("tokens") or []))


def long_prompt(
    url: str,
    model: str,
    target_tokens: int,
    seed,
    *,
    question: str,
    needles: list[tuple[float, str]] | None = None,
) -> tuple[str, int | None]:
    """Build a user prompt of ~target_tokens: unique salt first (defeats prefix
    reuse across seeds), filler, needle sentences at depth fractions, question last.
    Calibrated against /tokenize; falls back to 1.3 tokens/word when it is absent."""

    def build(n_words: int) -> str:
        body = filler_text(n_words, seed)
        if needles:
            words = body.split(" ")
            for depth, sentence in sorted(needles, reverse=True):
                i = max(1, int(len(words) * depth))
                while i < len(words) and not words[i - 1].endswith("."):
                    i += 1
                words.insert(i, sentence)
            body = " ".join(words)
        return f"[doc {seed}]\n{body}\n\n{question}"

    n_words = max(16, int(target_tokens / 1.3))
    text = build(n_words)
    got = count_tokens(url, model, [{"role": "user", "content": text}])
    if got:
        n_words = max(16, int(n_words * target_tokens / got))
        text = build(n_words)
        got = count_tokens(url, model, [{"role": "user", "content": text}])
    return text, got


# --------------------------------------------------------------------------- images


def _png_chunk(tag: bytes, data: bytes) -> bytes:
    return (
        len(data).to_bytes(4, "big")
        + tag
        + data
        + (zlib.crc32(tag + data) & 0xFFFFFFFF).to_bytes(4, "big")
    )


def grid_png(width: int, height: int, *, cols: int = 8, rows: int = 6, salt=0) -> bytes:
    """Stdlib RGB PNG: a cols x rows grid of colour blocks. `salt` changes the
    colours, so each send is a distinct image (defeats vLLM's mm processor cache)."""
    rng = random.Random(f"grid:{salt}")
    palette = [[bytes(rng.randrange(256) for _ in range(3)) for _ in range(cols)] for _ in range(rows)]
    comp = zlib.compressobj(6)
    parts = [b"\x89PNG\r\n\x1a\n", _png_chunk(b"IHDR", width.to_bytes(4, "big") + height.to_bytes(4, "big") + b"\x08\x02\x00\x00\x00")]
    idat: list[bytes] = []
    for r in range(rows):
        y0, y1 = r * height // rows, (r + 1) * height // rows
        line = bytearray(b"\x00")
        for c in range(cols):
            x0, x1 = c * width // cols, (c + 1) * width // cols
            line += palette[r][c] * (x1 - x0)
        idat.append(comp.compress(bytes(line) * (y1 - y0)))
    idat.append(comp.flush())
    parts.append(_png_chunk(b"IDAT", b"".join(idat)))
    parts.append(_png_chunk(b"IEND", b""))
    return b"".join(parts)


