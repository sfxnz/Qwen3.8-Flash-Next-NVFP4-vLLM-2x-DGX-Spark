# --------------------------------------------------------------------------- freeze


def file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_manifest(path: Path = MANIFEST) -> tuple[str, dict[str, str]]:
    version = "0"
    shas: dict[str, str] = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("version:"):
            version = line.split(":", 1)[1].strip()
            continue
        sha, rel = line.split(None, 1)
        shas[rel.strip()] = sha
    return version, shas


def current_shas() -> dict[str, str]:
    return {rel: file_sha256(ROOT / rel) for rel in FROZEN if (ROOT / rel).is_file()}


def drift() -> list[str]:
    """Frozen paths whose sha differs from the manifest (or are missing)."""
    try:
        _, pinned = read_manifest()
    except OSError:
        return list(FROZEN)
    now = current_shas()
    return sorted(rel for rel in set(pinned) | set(FROZEN) if pinned.get(rel) != now.get(rel))


def write_manifest(version: str) -> None:
    lines = [
        "# RULER_SET: companion ruler manifest (plan 0-7). Generated by",
        "# `python3 rulers/common.py --write --version N`. Do not hand-edit.",
        f"version: {version}",
    ]
    lines += [f"{sha}  {rel}" for rel, sha in current_shas().items()]
    MANIFEST.write_text("\n".join(lines) + "\n")


_IDENTITY_CACHE: dict[str, dict] = {}


def ruler_identity(script: str) -> dict:
    """Fields every evidence row carries: ruler name, RULER_SET version, script sha."""
    if script in _IDENTITY_CACHE:
        return _IDENTITY_CACHE[script]
    path = Path(script).resolve()
    try:
        version, _ = read_manifest()
    except OSError:
        version = "0"
    bad = drift()
    if bad:
        print(f"WARN ruler_set drift: {bad}", file=sys.stderr, flush=True)
    ident = {
        "ruler": path.stem,
        "ruler_set": version if not bad else f"{version}-dirty",
        "ruler_sha": file_sha256(path)[:12],
    }
    _IDENTITY_CACHE[script] = ident
    return ident


# --------------------------------------------------------------------------- output


class Emitter:
    """Print `ROW {json}` lines and append them to an fsync'd JSONL file."""

    def __init__(self, script: str, out: str | None, **meta) -> None:
        self.ident = ruler_identity(script)
        self.meta = meta
        self.out = Path(out) if out else None
        self.lock = threading.Lock()
        if self.out:
            self.out.parent.mkdir(parents=True, exist_ok=True)

    def row(self, kind: str, **fields) -> dict:
        rec = {**self.ident, "kind": kind, "ts": round(time.time(), 3), **self.meta, **fields}
        line = json.dumps(rec, sort_keys=False, default=_json_default)
        with self.lock:
            print("ROW", line, flush=True)
            if self.out:
                with self.out.open("a") as fh:
                    fh.write(line + "\n")
                    fh.flush()
                    os.fsync(fh.fileno())
        return rec

    def summary(self, obj) -> None:
        payload = {**self.ident, **self.meta, "summary": obj}
        print("SUMMARY", json.dumps(payload, indent=2, default=_json_default), flush=True)
        if self.out:
            self.row("summary", summary=obj)


def _json_default(o):
    if isinstance(o, float):
        return round(o, 6)
    return str(o)


def add_common_args(p: argparse.ArgumentParser) -> None:
    p.add_argument("--url", default=DEFAULT_URL)
    p.add_argument("--model", default=DEFAULT_MODEL)
    p.add_argument("--out", default=None, help="append evidence rows to this JSONL file")
    p.add_argument("--label", default="", help="free-text arm label copied into every row")


def base_url(url: str) -> str:
    return url.split("/v1/", 1)[0]


def metrics_url(url: str) -> str:
    return base_url(url) + "/metrics"


def health_ok(url: str, timeout: float = 5.0) -> bool:
    try:
        with urllib.request.urlopen(base_url(url) + "/health", timeout=timeout) as r:
            return r.status == 200
    except (OSError, urllib.error.URLError):
        return False


def require_health(url: str) -> None:
    if not health_ok(url):
        raise SystemExit(f"server not healthy at {base_url(url)}/health")


# --------------------------------------------------------------------------- stats


def pct(values, p: float) -> float | None:
    """Linear-interpolated percentile, p in [0, 100]. None on empty input."""
    vals = sorted(values)
    if not vals:
        return None
    if len(vals) == 1:
        return float(vals[0])
    k = (len(vals) - 1) * p / 100.0
    lo = int(k)
    hi = min(lo + 1, len(vals) - 1)
    return float(vals[lo] + (vals[hi] - vals[lo]) * (k - lo))


def med(values) -> float | None:
    vals = list(values)
    return float(statistics.median(vals)) if vals else None


def rnd(x, nd: int = 3):
    return None if x is None else round(float(x), nd)


def stable_seed(*parts) -> int:
    """seed = hash(prompt_id, rep), stable across processes (unlike hash())."""
    h = hashlib.sha256("\x1f".join(str(p) for p in parts).encode()).digest()
    return int.from_bytes(h[:4], "big") & 0x7FFFFFFF


def text_sha(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8", "replace")).hexdigest()[:16]


# --------------------------------------------------------------------------- metrics


def scrape(url: str, timeout: float = 10.0) -> dict[str, float] | None:
    """Prometheus text -> {metric_name: value summed over label sets}. Skips buckets."""
    try:
        with urllib.request.urlopen(metrics_url(url), timeout=timeout) as resp:
            text = resp.read().decode("utf-8", "replace")
    except (OSError, urllib.error.URLError):
        return None
    return parse_prom(text)


def parse_prom(text: str) -> dict[str, float]:
    out: dict[str, float] = {}
    for line in text.splitlines():
        if not line or line.startswith("#"):
            continue
        name = line.split("{", 1)[0].split(" ", 1)[0]
        if name.endswith("_bucket") or name.endswith("_created"):
            continue
        try:
            val = float(line.rsplit(" ", 1)[1])
        except (IndexError, ValueError):
            continue
        out[name] = out.get(name, 0.0) + val
    return out


def mget(m: dict[str, float] | None, name: str) -> float | None:
    """Read a counter by bare name, accepting the prometheus `_total` suffix."""
    if m is None:
        return None
    for key in (name + "_total", name):
        if key in m:
            return m[key]
    return None


def mdelta(before, after, name: str) -> float | None:
    a, b = mget(after, name), mget(before, name)
    return None if a is None or b is None else a - b


def spec_from_scrape(m: dict[str, float] | None) -> dict[str, float] | None:
    """Same shape as bench_decode.spec_counters(), from one scrape."""
    if m is None:
        return None
    out = {}
    for c in ("num_drafts", "num_draft_tokens", "num_accepted_tokens"):
        v = mget(m, f"vllm:spec_decode_{c}")
        if v is None:
            return None
        out[c] = v
    return out


def busy(url: str) -> float | None:
    """Running + waiting requests right now (other agents share the dev server)."""
    m = scrape(url)
    if m is None:
        return None
    return (mget(m, "vllm:num_requests_running") or 0.0) + (mget(m, "vllm:num_requests_waiting") or 0.0)


