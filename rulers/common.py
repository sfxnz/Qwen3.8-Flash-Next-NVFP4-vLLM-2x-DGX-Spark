def stream_chat(
    url: str,
    body: dict,
    *,
    timeout: float = 600.0,
    stop: threading.Event | None = None,
    t_ref: float | None = None,
) -> dict:
    """Stream one /v1/chat/completions request and time every delta chunk.

    Mirrors bench_decode.stream_one (include_usage, one chunk = one engine step
    with stream_interval 1) but also counts reasoning and tool-call deltas, keeps
    every chunk timestamp, and never raises: failures land in row["error"].
    `stop` aborts the stream by closing the connection (vLLM aborts the request).
    """
    body = {**body, "stream": True, "stream_options": {"include_usage": True}}
    req = urllib.request.Request(
        url, data=json.dumps(body).encode(), headers={"Content-Type": "application/json"}, method="POST"
    )
    t0 = time.perf_counter()
    row: dict = {
        "t_send": t0 - (t_ref if t_ref is not None else t0),
        "times": [],
        "content_chunks": 0,
        "reasoning_chunks": 0,
        "tool_chunks": 0,
        "tool_arg_len": [],
        "first_content_t": None,
        "finish_reason": None,
        "usage": {},
        "aborted": False,
        "error": None,
    }
    content: list[str] = []
    reasoning: list[str] = []
    calls: dict[int, dict] = {}
    arg_total = 0
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            for raw in resp:
                if stop is not None and stop.is_set():
                    row["aborted"] = True
                    break
                line = raw.decode("utf-8", "replace").strip()
                if not line.startswith("data:"):
                    continue
                payload = line[5:].strip()
                if payload == "[DONE]":
                    break
                try:
                    ev = json.loads(payload)
                except json.JSONDecodeError:
                    continue
                now = time.perf_counter()
                if ev.get("usage"):
                    row["usage"] = ev["usage"]
                choices = ev.get("choices") or []
                if not choices:
                    continue
                ch = choices[0]
                if ch.get("finish_reason"):
                    row["finish_reason"] = ch["finish_reason"]
                delta = ch.get("delta") or {}
                got = False
                c = delta.get("content") or ""
                if c:
                    content.append(c)
                    row["content_chunks"] += 1
                    if row["first_content_t"] is None:
                        row["first_content_t"] = now - t0
                    got = True
                r = delta.get("reasoning") or delta.get("reasoning_content") or ""
                if r:
                    reasoning.append(r)
                    row["reasoning_chunks"] += 1
                    got = True
                for tc in delta.get("tool_calls") or []:
                    slot = calls.setdefault(int(tc.get("index", 0)), {"name": "", "arguments": ""})
                    fn = tc.get("function") or {}
                    if fn.get("name"):
                        slot["name"] += fn["name"]
                    a = fn.get("arguments") or ""
                    if a:
                        slot["arguments"] += a
                        arg_total += len(a)
                    row["tool_chunks"] += 1
                    got = True
                if got:
                    row["times"].append(now - t0)
                    if calls:
                        row["tool_arg_len"].append(arg_total)
    except urllib.error.HTTPError as exc:
        row["error"] = f"HTTP {exc.code}: {exc.read().decode('utf-8', 'replace')[:500]}"
    except Exception as exc:  # noqa: BLE001 - reported per row, never fatal to a wave
        row["error"] = f"{type(exc).__name__}: {exc}"
    row["total_s"] = time.perf_counter() - t0
    row["content"] = "".join(content)
    row["reasoning"] = "".join(reasoning)
    row["tool_calls"] = [calls[k] for k in sorted(calls)]
    return row


def step_stats(row: dict) -> dict:
    """ms/step from chunk timestamps: decode_s / (chunks - 1), plus ITL percentiles."""
    t = row["times"]
    usage = row.get("usage") or {}
    completion = int(usage.get("completion_tokens") or 0)
    out = {
        "ttft_s": rnd(t[0]) if t else None,
        "chunks": len(t),
        "completion_tokens": completion,
        "prompt_tokens": int(usage.get("prompt_tokens") or 0),
        "cached_tokens": ((usage.get("prompt_tokens_details") or {}).get("cached_tokens")),
        "finish_reason": row.get("finish_reason"),
        "error": row.get("error"),
    }
    if len(t) >= 2:
        decode_s = t[-1] - t[0]
        gaps = [(b - a) * 1000.0 for a, b in zip(t, t[1:])]
        out.update(
            decode_s=rnd(decode_s, 4),
            ms_per_step=rnd(decode_s * 1000.0 / (len(t) - 1)),
            tokens_per_step=rnd((completion - 1) / (len(t) - 1)) if completion else None,
            decode_tok_s=rnd((completion - 1) / decode_s) if completion and decode_s > 0 else None,
            itl_p50_ms=rnd(pct(gaps, 50)),
            itl_p99_ms=rnd(pct(gaps, 99)),
            itl_max_ms=rnd(max(gaps)),
        )
    return out


def gaps_in_window(times_abs: list[float], lo: float, hi: float) -> list[float]:
    """Inter-chunk gaps (ms) whose end falls inside [lo, hi] on a shared clock."""
    return [(b - a) * 1000.0 for a, b in zip(times_abs, times_abs[1:]) if lo <= b <= hi]


def chat_body(model: str, messages, max_tokens: int, *, thinking: bool = False, **extra) -> dict:
    if isinstance(messages, str):
        messages = [{"role": "user", "content": messages}]
    body = {
        "model": model,
        "messages": messages,
        "max_tokens": max_tokens,
        "temperature": 0,
        "chat_template_kwargs": {"enable_thinking": thinking},
    }
    body.update(extra)
    return body


