def run_cmd(cmd: list[str], timeout: float = 15.0) -> str:
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, check=False).stdout
    except (OSError, subprocess.TimeoutExpired) as exc:
        return f"ERR {exc}"


class HostSampler(threading.Thread):
    """Every `period` s: `free -h` and one vmstat line on the head and (read-only,
    over ssh BatchMode) on the worker. Writes a JSONL log next to --out."""

    CMD = "free -h; vmstat 1 2 | tail -1"

    def __init__(self, log_path: Path, worker: str | None, period: float = 5.0) -> None:
        super().__init__(daemon=True)
        self.log_path = log_path
        self.worker = worker
        self.period = period
        self.halt = threading.Event()
        self.samples = 0

    def _sample(self, host: str | None) -> str:
        if host is None:
            return run_cmd(["sh", "-c", self.CMD])
        return run_cmd(["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=5", host, self.CMD])

    def run(self) -> None:
        self.log_path.parent.mkdir(parents=True, exist_ok=True)
        with self.log_path.open("a") as fh:
            while not self.halt.is_set():
                t = time.time()
                hosts = [("head", None)] + ([("worker", self.worker)] if self.worker else [])
                for name, host in hosts:
                    fh.write(json.dumps({"ts": round(t, 3), "node": name, "out": self._sample(host)}) + "\n")
                fh.flush()
                self.samples += 1
                self.halt.wait(max(0.0, self.period - (time.time() - t)))

    def stop(self) -> None:
        self.halt.set()
        self.join(timeout=30)


# --------------------------------------------------------------------------- CLI


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true", help="exit 1 when a frozen file drifted")
    g.add_argument("--write", action="store_true", help="rewrite RULER_SET from the current tree")
    p.add_argument("--version", help="RULER_SET version to write (required with --write)")
    args = p.parse_args()
    if args.write:
        if not args.version:
            p.error("--write needs --version")
        write_manifest(args.version)
        print(f"wrote {MANIFEST} version {args.version}")
        return 0
    bad = drift()
    version, _ = read_manifest()
    if bad:
        print(f"RULER_SET {version} drift: {bad}", file=sys.stderr)
        return 1
    print(f"RULER_SET {version} ok ({len(FROZEN)} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
