def load_prompts(name: str) -> dict:
    return json.loads((PROMPTS_DIR / f"{name}.json").read_text())


def diverse_items(categories=("prose", "structured"), limit: int | None = None) -> list[dict]:
    data = load_prompts("diverse")
    items: list[dict] = []
    for cat in categories:
        rows = data[cat][:limit] if limit else data[cat]
        for r in rows:
            item = {**r, "category": cat}
            if r.get("tool"):
                item["tools"] = [data["tools"][r["tool"]]]
            items.append(item)
    return items


def item_body(model: str, item: dict, max_tokens: int, **extra) -> dict:
    body = chat_body(model, item["prompt"], max_tokens, **extra)
    if item.get("tools"):
        body["tools"] = item["tools"]
        body["tool_choice"] = "auto"
    return body


