#!/usr/bin/env python3
"""Shared stdlib helpers for the companion rulers (plan item 0-7).

Every companion ruler is a separate script frozen by sha256 in rulers/RULER_SET.
This module is frozen with them. bench_decode.py is also listed there, because
the rulers import PHASES, spec_counters and acceptance from it unchanged.

Maintenance:
    python3 rulers/common.py --check           # exit 1 when a frozen file drifted
    python3 rulers/common.py --write --version 2   # re-freeze after an intended change

Bump the version whenever a frozen file changes. Evidence rows carry the version
in "ruler_set"; a drifted tree reports "<version>-dirty" so it cannot pass as frozen.
"""

